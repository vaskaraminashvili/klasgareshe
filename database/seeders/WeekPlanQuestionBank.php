    /**
     * @param  list<array{0: string, 1: string, 2: list<string>, 3: string}>  $rows
     * @return list<array{prompt: string, correct: string, wrongs: list<string>, emoji: string}>
     */
    private static function mapRows(array $rows): array
    {
        $questions = [];

        foreach ($rows as $row) {
            $questions[] = self::q($row[0], $row[1], $row[2], $row[3]);
        }

        return $questions;
    }

    /**
     * @param  list<string>  $wrongs
     * @return array{prompt: string, correct: string, wrongs: list<string>, emoji: string}
     */
    private static function q(string $prompt, string $correct, array $wrongs, string $emoji): array
    {
        $clean = [];

        foreach ($wrongs as $wrong) {
            if ($wrong !== $correct && ! in_array($wrong, $clean, true)) {
                $clean[] = $wrong;
            }
        }

        while (count($clean) < 3) {
            $clean[] = $correct.'·'.(string) (count($clean) + 1);
        }

        return [
            'prompt' => $prompt,
            'correct' => $correct,
            'wrongs' => array_slice($clean, 0, 3),
            'emoji' => $emoji,
        ];
    }
