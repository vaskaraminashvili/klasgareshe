    private static function rangePack(SchoolGrade $grade, int $from, int $to): array
    {
        $shift = match ($grade) {
            SchoolGrade::First => 0,
            SchoolGrade::Second => 10,
            SchoolGrade::Third => 30,
        };

        $questions = [];
        $emojis = ['1️⃣', '2️⃣', '3️⃣', '4️⃣', '5️⃣'];

        for ($i = 0; $i < 5; $i++) {
            $n = $from + $i + $shift;
            $questions[] = self::q(
                'რომელია რიცხვი '.$n.'?',
                (string) $n,
                [(string) ($n + 1), (string) ($n - 1), (string) ($n + 2)],
                $emojis[$i],
            );
        }

        return $questions;
    }

