    public static function gameType(
        SchoolGrade $grade,
        SchoolSubject $subject,
        int $weekday,
        int $weekNumber,
    ): ?GameType {
        if ($weekNumber !== 1) {
            return null;
        }

        if ($subject === SchoolSubject::Georgian) {
            return match ($weekday) {
                2 => GameType::TraceLetter,
                3 => GameType::SpellWord,
                4 => GameType::FillLetter,
                5 => GameType::Opposites,
                6 => GameType::MatchWord,
                7 => GameType::WordSearch,
                default => null,
            };
        }

        if ($subject === SchoolSubject::History) {
            return match ($weekday) {
                5 => GameType::Knowledge,
                6 => GameType::ConnectPair,
                default => null,
            };
        }

        return null;
    }

    /**
     * @return array{title: string, questions: list<array{prompt: string, correct: string, wrongs: list<string>, emoji: string, difficulty: string}>}|null
     */
    public static function pack(
        SchoolGrade $grade,
        SchoolSubject $subject,
        int $weekday,
        int $weekNumber,
    ): ?array {
        $type = self::gameType($grade, $subject, $weekday, $weekNumber);

        if ($type === null) {
            return null;
        }

        $title = match ($type) {
            GameType::TraceLetter => 'ასოს წერა',
            GameType::SpellWord => 'დაწერე სიტყვა',
            GameType::FillLetter => 'გამოტოვებული ასო',
            GameType::Opposites => 'საპირისპირო სიტყვები',
            GameType::MatchWord => 'სიტყვა და სურათი',
            GameType::WordSearch => 'სიტყვის ძიება',
            GameType::Knowledge => 'ცოდნის ქვიზი',
            GameType::ConnectPair => 'წყვილების შეერთება',
            default => $type->title(),
        };

        if ($grade === SchoolGrade::Second) {
            $title .= ' · II';
        }

        if ($grade === SchoolGrade::Third) {
            $title .= ' · III';
        }

        return [
            'title' => $title,
            'questions' => self::questions($type, $grade),
        ];
    }

    /**
     * @return list<array{prompt: string, correct: string, wrongs: list<string>, emoji: string, difficulty: string}>
     */
    private static function questions(GameType $type, SchoolGrade $grade): array
    {
        $level = $grade->value;

        return match ($type) {
            GameType::FillLetter => self::tagged($level, self::fill()),
            GameType::SpellWord => self::spellRows($level),
            GameType::TraceLetter => self::traceRows($level),
            GameType::MatchWord => self::matchRows($level),
            GameType::WordSearch => self::searchRows($level),
            GameType::Opposites => self::tagged($level, self::opposites()),
            GameType::Knowledge => self::tagged($level, self::knowledge()),
            GameType::ConnectPair => self::connectRows($level),
            default => [],
        };
    }

    /**
     * @param  array<int, array<string, list<array{0: string, 1: string, 2: list<string>, 3: string}>>>  $catalog
     * @return list<array{prompt: string, correct: string, wrongs: list<string>, emoji: string, difficulty: string}>
     */
    private static function tagged(int $grade, array $catalog): array
    {
        $rows = [];

        foreach (['easy', 'medium', 'hard'] as $difficulty) {
            foreach ($catalog[$grade][$difficulty] as $tuple) {
                $rows[] = [
                    'prompt' => $tuple[0],
                    'correct' => $tuple[1],
                    'wrongs' => $tuple[2],
                    'emoji' => $tuple[3],
                    'difficulty' => $difficulty,
                ];
            }
        }

        return $rows;
    }

    /**
     * @return list<array{prompt: string, correct: string, wrongs: list<string>, emoji: string, difficulty: string, keyboard: list<string>, slots: int}>
     */
    private static function spellRows(int $grade): array
    {
        $rows = [];

        foreach (self::spell()[$grade] as $difficulty => $items) {
            foreach ($items as $item) {
                $rows[] = [
                    'prompt' => $item[0],
                    'correct' => $item[1],
                    'wrongs' => $item[2],
                    'emoji' => $item[3],
                    'difficulty' => $difficulty,
                    'keyboard' => self::keyboard($item[1]),
                    'slots' => mb_strlen($item[1]),
                ];
            }
        }

        return $rows;
    }

    /**
     * @return list<array{prompt: string, correct: string, wrongs: list<string>, emoji: string, difficulty: string, strokes: list<list<array{0: int, 1: int}>>}>
     */
    private static function traceRows(int $grade): array
    {
        $rows = [];
        $decoys = ['ა', 'ბ', 'გ', 'დ', 'ე', 'ვ', 'ზ', 'თ'];

        foreach (self::trace()[$grade] as $difficulty => $letters) {
            foreach ($letters as $letter) {
                $wrongs = [];

                foreach ($decoys as $decoy) {
                    if ($decoy !== $letter) {
                        $wrongs[] = $decoy;
                    }

                    if (count($wrongs) === 3) {
                        break;
                    }
                }

                $rows[] = [
                    'prompt' => $letter,
                    'correct' => $letter,
                    'wrongs' => $wrongs,
                    'emoji' => '✏️',
                    'difficulty' => $difficulty,
                    'strokes' => GeorgianLetterStrokes::for($letter),
                ];
            }
        }

        return $rows;
    }

    /**
     * @return list<array{prompt: string, correct: string, wrongs: list<string>, emoji: string, difficulty: string}>
     */
    private static function matchRows(int $grade): array
    {
        $rows = [];

        foreach (self::match()[$grade] as $difficulty => $pairs) {
            foreach ($pairs as $pair) {
                $wrongs = [];

                foreach ($pairs as $other) {
                    if ($other[1] !== $pair[1]) {
                        $wrongs[] = $other[1];
                    }
                }

                $rows[] = [
                    'prompt' => $pair[0],
                    'correct' => $pair[1],
                    'wrongs' => array_slice($wrongs, 0, 3),
                    'emoji' => $pair[1],
                    'difficulty' => $difficulty,
                ];
            }
        }

        return $rows;
    }

    /**
     * @return list<array{prompt: string, correct: string, wrongs: list<string>, emoji: string, difficulty: string}>
     */
    private static function searchRows(int $grade): array
    {
        $rows = [];

        foreach (self::search()[$grade] as $difficulty => $words) {
            foreach ($words as $word) {
                $wrongs = [];

                foreach ($words as $other) {
                    if ($other[0] !== $word[0]) {
                        $wrongs[] = $other[0];
                    }
                }

                $rows[] = [
                    'prompt' => $word[0],
                    'correct' => $word[0],
                    'wrongs' => array_slice($wrongs, 0, 3),
                    'emoji' => $word[1],
                    'difficulty' => $difficulty,
                ];
            }
        }

        return $rows;
    }

    /**
     * @return list<array{prompt: string, correct: string, wrongs: list<string>, emoji: string, difficulty: string, match_emoji: string}>
     */
    private static function connectRows(int $grade): array
    {
        $rows = [];

        foreach (self::connect()[$grade] as $difficulty => $pairs) {
            foreach ($pairs as $pair) {
                $wrongs = [];

                foreach ($pairs as $other) {
                    if ($other[2] !== $pair[2]) {
                        $wrongs[] = $other[2];
                    }
                }

                $rows[] = [
                    'prompt' => $pair[0],
                    'correct' => $pair[2],
                    'wrongs' => array_slice($wrongs, 0, 3),
                    'emoji' => $pair[1],
                    'match_emoji' => $pair[3],
                    'difficulty' => $difficulty,
                ];
            }
        }

        return $rows;
    }

    /**
     * @return list<string>
     */
    private static function keyboard(string $word): array
    {
        $letters = [];

        foreach (mb_str_split($word) as $letter) {
            $letters[$letter] = $letter;
        }

        foreach (mb_str_split('აეიოუბგდვზთკლმნსპრტქ') as $letter) {
            if (count($letters) >= mb_strlen($word) + 3) {
                break;
            }

            $letters[$letter] = $letter;
        }

        return array_values($letters);
    }

