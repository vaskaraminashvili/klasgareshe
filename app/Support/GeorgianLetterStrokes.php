<?php

namespace App\Support;

class GeorgianLetterStrokes
{
    /**
     * Guide polylines in the template's 200×220 viewBox.
     * A missing letter falls back to a simple peak so the tracer still has a path.
     *
     * @return list<list<array{0: int, 1: int}>>
     */
    public static function for(string $letter): array
    {
        $known = self::known();

        if (isset($known[$letter])) {
            return $known[$letter];
        }

        $n = abs(mb_ord($letter)) % 4;

        return match ($n) {
            0 => [[[40, 180], [100, 40], [160, 180]], [[70, 120], [130, 120]]],
            1 => [[[50, 36], [50, 184], [150, 184]], [[50, 100], [130, 100]]],
            2 => [[[36, 40], [164, 40], [164, 180], [36, 180], [36, 40]]],
            default => [[[40, 40], [160, 40], [100, 180], [40, 40]]],
        };
    }

